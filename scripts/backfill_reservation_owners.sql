-- Выполнять после onebase migrate. Совместимо с SQLite и PostgreSQL.
-- Наименование владельца может меняться. Связываем оба объекта по идентификаторам.
UPDATE рег_резервытоваров
SET ключорганизации = CAST(з.организация_id AS TEXT)
FROM заказпокупателя AS з
WHERE рег_резервытоваров.заказпокупателя_id = з.id
  AND (рег_резервытоваров.ключорганизации IS NULL OR рег_резервытоваров.ключорганизации = '')
  AND з.организация_id IS NOT NULL;
